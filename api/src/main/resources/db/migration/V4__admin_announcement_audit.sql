CREATE TABLE IF NOT EXISTS public_admin_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(64) NOT NULL,
    action VARCHAR(64) NOT NULL,
    entity_type VARCHAR(32) NOT NULL,
    entity_id BIGINT NOT NULL,
    reason VARCHAR(500) NOT NULL,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_public_admin_audit_entity
    ON public_admin_audit (entity_type, entity_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_public_admin_audit_created
    ON public_admin_audit (created_at DESC);
